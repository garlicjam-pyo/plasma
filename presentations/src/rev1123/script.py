SEC = {1: 25, 2: 30, 3: 110, 4: 110, 5: 80, 6: 95, 7: 105, 8: 115, 9: 80, 10: 125, 11: 50, 12: 120, 13: 90, 14: 65}
assert sum(SEC.values()) == 1200


def timing():
    t, out = 0, {}
    for k in sorted(SEC):
        out[k] = (t, t + SEC[k], SEC[k]); t += SEC[k]
    return out


def mmss(x):
    return f"{x // 60}:{x % 60:02d}"


def note_text(page):
    a, b, s = timing()[page]
    return f"[대본 · {mmss(a)}–{mmss(b)} / {s}초]\n" + "\n".join(S[page][1])
